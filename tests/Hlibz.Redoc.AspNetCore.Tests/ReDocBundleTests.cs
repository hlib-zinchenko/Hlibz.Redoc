using System.IO.Compression;
using System.Reflection;
using System.Security.Cryptography;
using System.Text;

using Xunit;

namespace Hlibz.Redoc.Extensions.Tests;

/// <summary>
/// The embedded ReDoc bundle: that it is there in both encodings, that they are the same file,
/// that it is the version this package claims, and that it survives the round trip out of the
/// assembly.
/// </summary>
/// <remarks>
/// Worth asserting because the failure mode is quiet: an <c>EmbeddedResource</c> that stops
/// matching its file, a bundle upgraded without updating <see cref="ReDocBundle.Version"/>, or one
/// of the two compressed copies regenerated without the other, produces a package that looks fine
/// until someone opens a page.
/// </remarks>
public class ReDocBundleTests
{
    [Fact]
    public void BothEncodings_AreEmbedded()
    {
        Assert.True(ReDocBundle.Gzip.Bytes.Length > 100_000);
        Assert.True(ReDocBundle.Brotli.Bytes.Length > 100_000);
    }

    [Fact]
    public void BothEncodings_DecodeToTheSameBundle()
    {
        // The two files are generated by hand on an upgrade, so this is the guard against
        // shipping a brotli copy of one version and a gzip copy of another — which would show up
        // only as "the page works in Safari and not in Chrome", or the reverse.
        byte[] fromGzip = ReDocBundle.Identity.Bytes.ToArray();
        byte[] fromBrotli = DecompressBrotli(ReDocBundle.Brotli.Bytes.ToArray());

        Assert.Equal(fromGzip.Length, fromBrotli.Length);
        Assert.True(fromGzip.AsSpan().SequenceEqual(fromBrotli));
    }

    [Fact]
    public void Identity_IsTheVersionTheConstantClaims()
    {
        string bundle = Encoding.UTF8.GetString(ReDocBundle.Identity.Bytes.Span);

        // ReDoc prints its own version to the console on startup, so the bundle carries the
        // string: the one place the file itself can be asked what it is.
        Assert.Contains(ReDocBundle.Version, bundle, StringComparison.Ordinal);
    }

    [Fact]
    public void Identity_IsTheWholeBundle()
    {
        ReadOnlyMemory<byte> raw = ReDocBundle.Identity.Bytes;

        Assert.True(raw.Length > ReDocBundle.Gzip.Bytes.Length * 2);
        Assert.Contains(
            "Redocly",
            Encoding.UTF8.GetString(raw.Span[..2000]),
            StringComparison.Ordinal);
    }

    [Fact]
    public void ETag_IsStrongAndQuoted()
    {
        foreach (ReDocBundleContent content in
            new[] { ReDocBundle.Brotli, ReDocBundle.Gzip, ReDocBundle.Identity })
        {
            Assert.StartsWith("\"", content.ETag, StringComparison.Ordinal);
            Assert.EndsWith("\"", content.ETag, StringComparison.Ordinal);
        }
    }

    /// <summary>
    /// Everything <c>assets/README.md</c> records about the bundle, held against the bundle.
    /// </summary>
    /// <remarks>
    /// That table is where an upgrade is written down — which version, which file out of which
    /// tarball, and how big it came out — and until this test it was kept in step with the bundle
    /// by hand, with only the version loosely covered. Each row is now checked against the bytes
    /// in the assembly, so a bundle swapped in without updating the note fails here instead of
    /// quietly making the note a lie. The one row this can't reach is the tarball's own integrity
    /// hash, which belongs to a file that isn't in the repository.
    /// </remarks>
    [Fact]
    public void AssetsReadme_DescribesTheBundleThatShipped()
    {
        IReadOnlyDictionary<string, string> recorded = AssetsReadmeTable();

        Assert.Equal(ReDocBundle.Version, recorded["ReDoc"]);
        Assert.Contains(
            $"redoc-{ReDocBundle.Version}.tgz", recorded["npm tarball"], StringComparison.Ordinal);

        Assert.Equal(
            Convert.ToHexString(SHA256.HashData(ReDocBundle.Identity.Bytes.Span))
                .ToLowerInvariant(),
            recorded["that file, sha256"]);

        Assert.Equal(ReDocBundle.Identity.Bytes.Length, ByteCount(recorded["uncompressed"]));
        Assert.Equal(ReDocBundle.Gzip.Bytes.Length, ByteCount(recorded["as stored, gzip"]));
        Assert.Equal(ReDocBundle.Brotli.Bytes.Length, ByteCount(recorded["as stored, brotli"]));
    }

    /// <summary>The <c>| label | value |</c> rows of the note, as a lookup.</summary>
    private static IReadOnlyDictionary<string, string> AssetsReadmeTable()
    {
        using Stream stream = typeof(ReDocBundleTests).GetTypeInfo().Assembly
            .GetManifestResourceStream("assets-README.md")
            ?? throw new InvalidOperationException(
                "assets/README.md is not embedded in the test assembly; see the EmbeddedResource "
                + "in Hlibz.Redoc.AspNetCore.Tests.csproj.");

        using StreamReader reader = new(stream);
        Dictionary<string, string> rows = [];
        while (reader.ReadLine() is { } line)
        {
            string[] cells = line.Split('|', StringSplitOptions.TrimEntries);
            if (cells.Length != 4 || cells[1].Length == 0 || cells[1].StartsWith('-'))
            {
                continue;
            }

            rows[cells[1]] = cells[2].Trim('*', '`');
        }

        return rows;
    }

    /// <summary>A <c>2,290,276 bytes</c> cell as a number.</summary>
    private static int ByteCount(string cell) =>
        int.Parse(
            cell.Replace(" bytes", string.Empty, StringComparison.Ordinal)
                .Replace(",", string.Empty, StringComparison.Ordinal),
            System.Globalization.CultureInfo.InvariantCulture);

    private static byte[] DecompressBrotli(byte[] compressed)
    {
        using MemoryStream source = new(compressed, writable: false);
        using BrotliStream decompressor = new(source, CompressionMode.Decompress);
        using MemoryStream buffer = new(capacity: compressed.Length * 4);
        decompressor.CopyTo(buffer);
        return buffer.ToArray();
    }
}
